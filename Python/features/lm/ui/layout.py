"""Construct LM page widgets; session state and lifecycle stay outside this builder."""
from commonUtils.ui.pyside.passwords import password_field
from commonUtils.ui import pyside as qt
from commonUtils.ui.appearance.status_line import StatusLine
from .composer import Composer, SamplingSpin
from .conversation_view import ConversationView
from .conversation_tree import ConversationTree
from .icons import chat_icon
from .mode_tabs import ModeTabs
from .changes import ChangesPane
from .model_picker import ModelPicker


def build_layout(page):
    """Populate the page's widget references and return its top-level layout."""
    page.setAcceptDrops(True)
    page.setProperty('navigation_position', 'workspace')
    layout = qt.QVBoxLayout(page)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(0)
    splitter = qt.QSplitter()
    layout.addWidget(splitter, 1)
    _build_sidebar(page, splitter)
    right = page.chat_body = qt.QWidget()
    body = qt.QVBoxLayout(right)
    body.setContentsMargins(8, 4, 4, 4)
    body.setSpacing(6)
    _build_session_controls(page, body)
    _build_message_controls(page, body)
    page.content_splitter = qt.QSplitter()
    page.content_splitter.addWidget(right)
    page.changes_pane = ChangesPane()
    page.content_splitter.addWidget(page.changes_pane)
    page.content_splitter.setStretchFactor(0, 1)
    page.content_splitter.setStretchFactor(1, 1)
    page.content_splitter.setChildrenCollapsible(False)
    splitter.addWidget(page.content_splitter)
    splitter.setStretchFactor(1, 1)
    splitter.setSizes([245, 850])
    splitter.setHandleWidth(1)
    page.status = StatusLine('Ready.')
    page.status.setWordWrap(True)
    page.status.setTextFormat(qt.Qt.TextFormat.PlainText)
    page.status.setContentsMargins(0, 0, 0, 0)
    page.status_bar = qt.QStatusBar()
    page.status_bar.setSizeGripEnabled(False)
    content = qt.QWidget(page.status_bar)
    footer = qt.QHBoxLayout(content)
    footer.setContentsMargins(2, 2, 2, 2)
    footer.setSpacing(8)
    footer.addWidget(page.status, 1)
    page.status_bar.addWidget(content, 1)
    page.status_bar.setStyleSheet('QStatusBar::item { border: none; }')
    body.addWidget(page.status_bar)
    page.save_error = qt.QLabel()
    page.save_error.setWordWrap(True)
    page.save_error.setTextFormat(qt.Qt.TextFormat.PlainText)
    body.addWidget(page.save_error)
    page.save_error.hide()
    return layout


def _build_sidebar(page, splitter):
    left = page.sidebar = qt.QWidget()
    side = qt.QVBoxLayout(left)
    side.setContentsMargins(8, 8, 8, 8)
    side.setSpacing(10)
    page.mode = ModeTabs(left)
    side.addWidget(page.mode)
    page.search = qt.QLineEdit()
    page.search.setPlaceholderText('Search conversations…')
    side.addWidget(page.search)
    page.list = ConversationTree()
    page.list.move_requested.connect(page.conversations.move_tree_item)
    page.list.setContextMenuPolicy(qt.Qt.ContextMenuPolicy.CustomContextMenu)
    page.list.customContextMenuRequested.connect(page.conversations.conversation_menu)
    page.list.setHeaderHidden(True)
    page.list.setAccessibleName('Conversation folders and conversations')
    page.list.setIndentation(16)
    side.addWidget(page.list, 1)
    row = qt.QHBoxLayout()
    page.new_button = page.icon_button('New conversation', page.conversations.new_conversation, 'new', row)
    page.folder_button = page.icon_button('New folder…', page.conversations.new_folder, 'folder', row)
    page.refresh_button = page.icon_button('Refresh conversations', page.refresh, 'refresh', row)
    row.addStretch()
    page.more_button = qt.QToolButton()
    page.more_button.setIcon(chat_icon('more'))
    page.more_button.setIconSize(qt.QSize(20, 20))
    page.more_button.setAutoRaise(True)
    page.more_button.setToolTip('Conversation actions')
    page.more_button.setAccessibleName('Conversation actions')
    page.more_button.setPopupMode(qt.QToolButton.ToolButtonPopupMode.InstantPopup)
    menu = qt.QMenu(page.more_button)
    page.rename_button = menu.addAction('Rename conversation…', page.conversations.rename)
    page.move_button = menu.addAction('Move conversation…', page.conversations.move_conversation)
    page.export_button = menu.addAction('Export conversation…', page.conversations.export)
    page.pin_action = menu.addAction('Pin conversation', page.conversations.toggle_pin)
    page.fork_action = menu.addAction('Fork conversation', page.conversations.fork_conversation)
    menu.addSeparator()
    page.delete_button = menu.addAction('Delete conversation…', page.conversations.delete)
    page.more_button.setMenu(menu)
    row.addWidget(page.more_button)
    side.insertLayout(0, row)
    page.list.setFrameShape(qt.QFrame.Shape.NoFrame)
    page.list.setUniformRowHeights(True)
    splitter.addWidget(left)


def _build_session_controls(page, body):
    page.connection_box = qt.QWidget()
    connection = qt.QFormLayout(page.connection_box)
    connection.setContentsMargins(0, 0, 0, 0)
    row = qt.QHBoxLayout()
    page.profile = qt.QComboBox()
    page.profile.setMinimumContentsLength(12)
    page.profile.setSizeAdjustPolicy(qt.QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
    row.addWidget(page.profile, 1)
    page.profiles_button = page.icon_button('Manage server profiles', page.edit_profiles, 'settings', row)
    connection.addRow('Server', row)
    page.token = qt.QLineEdit()
    password_field(page.token)
    page.token.setPlaceholderText('Optional API token — session only')
    connection.addRow('Token', page.token)
    connection.setRowVisible(page.token, False)
    page.test_button = page.icon_button('Test connection / Refresh models', page.refresh_models, 'refresh', row)
    body.addWidget(page.connection_box)
    page.project_box = qt.QWidget()
    project_row = qt.QHBoxLayout(page.project_box)
    project_row.setContentsMargins(0, 0, 0, 0)
    page.project_picker = qt.QComboBox()
    page.project_picker.setAccessibleName('IDE project')
    page.project_picker.setMinimumContentsLength(12)
    page.project_picker.setSizeAdjustPolicy(qt.QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
    project_row.addWidget(page.project_picker, 1)
    page.project_refresh = page.button('Refresh projects', page.load_projects, project_row)
    page.allow_edits = qt.QCheckBox('Allow edits')
    page.allow_edits.setToolTip('Let the model save text edits directly. Pending editor changes and stale files are protected.')
    page.allow_edits.toggled.connect(page.project_changed)
    project_row.addWidget(page.allow_edits)
    body.addWidget(page.project_box)
    page.mode.currentChanged.connect(page.mode_changed)
    page.project_picker.currentIndexChanged.connect(page.project_changed)
    options = qt.QHBoxLayout()
    page.settings_toggle = qt.QToolButton()
    page.settings_toggle.setText('Generation settings')
    page.settings_toggle.setCheckable(True)
    page.settings_toggle.setAutoRaise(True)
    page.settings_toggle.setArrowType(qt.Qt.ArrowType.RightArrow)
    page.settings_toggle.setToolButtonStyle(qt.Qt.ToolButtonStyle.ToolButtonTextBesideIcon)
    options.addWidget(page.settings_toggle)
    page.auth_toggle = qt.QToolButton()
    page.auth_toggle.setText('Session token')
    page.auth_toggle.setCheckable(True)
    page.auth_toggle.setAutoRaise(True)
    page.auth_toggle.toggled.connect(lambda shown: connection.setRowVisible(page.token, shown))
    options.addStretch()
    options.addWidget(page.auth_toggle)
    body.addLayout(options)
    page.settings_box = qt.QWidget()
    settings = qt.QFormLayout(page.settings_box)
    page.temperature = SamplingSpin()
    page.temperature.setRange(-1, 2)
    page.temperature.setSingleStep(.1)
    page.temperature.setSpecialValueText('Server default')
    settings.addRow('Temperature', page.temperature)
    page.top_p = SamplingSpin()
    page.top_p.setRange(-1, 1)
    page.top_p.setSingleStep(.05)
    page.top_p.setSpecialValueText('Server default')
    settings.addRow('Top-p', page.top_p)
    page.context = qt.QSpinBox()
    page.context.setRange(256, 2_000_000)
    settings.addRow('Model context size (tokens)', page.context)
    page.max_tokens = qt.QSpinBox()
    page.max_tokens.setRange(1, 131072)
    settings.addRow('Maximum response tokens', page.max_tokens)
    page.system = qt.QPlainTextEdit()
    page.system.setPlaceholderText('System instructions')
    page.system.setMaximumHeight(90)
    settings.addRow('System instructions', page.system)
    note = qt.QLabel('Context uses an approximate UTF-8 token estimate. Set the context size to match your server model. Older turns may be omitted; saved history stays intact.')
    note.setWordWrap(True)
    settings.addRow(note)
    body.addWidget(page.settings_box)
    page.settings_box.hide()
    page.settings_toggle.toggled.connect(page.settings_box.setVisible)
    page.settings_toggle.toggled.connect(lambda shown: page.settings_toggle.setArrowType(
        qt.Qt.ArrowType.DownArrow if shown else qt.Qt.ArrowType.RightArrow))


def _build_message_controls(page, body):
    page.transcript = ConversationView()
    page.transcript.setAccessibleName('Conversation transcript')
    page.transcript.retry_requested.connect(page.retry)
    page.transcript.changes_requested.connect(page.show_changes)
    page.transcript.edit_requested.connect(page.edit_changed_file)
    page.transcript.undo_requested.connect(page.undo_changes)
    page.message_surface = qt.QWidget()
    surface = qt.QGridLayout(page.message_surface)
    surface.setContentsMargins(0, 0, 0, 0)
    surface.setSpacing(0)
    surface.setColumnStretch(0, 1)
    # Leave the transcript's entire scrollbar accessible beside the floating draft.
    surface.setColumnMinimumWidth(1, page.transcript.verticalScrollBar().sizeHint().width() + 4)
    surface.addWidget(page.transcript, 0, 0, 1, 2)
    body.addWidget(page.message_surface, 1)
    page.composer_dock = qt.QWidget()
    dock = qt.QVBoxLayout(page.composer_dock)
    dock.setContentsMargins(12, 6, 8, 12)
    dock.setSpacing(6)
    surface.addWidget(page.composer_dock, 0, 0, qt.Qt.AlignmentFlag.AlignBottom)
    page.composer_dock.raise_()
    page.disclaimer = qt.QLabel('Language Models can make mistakes. Check important info.')
    page.disclaimer.setAlignment(qt.Qt.AlignmentFlag.AlignCenter)
    page.disclaimer.setWordWrap(True)
    page.disclaimer.setSizePolicy(qt.QSizePolicy.Policy.Preferred, qt.QSizePolicy.Policy.Maximum)
    dock.addWidget(page.disclaimer)
    page.image_drafts = qt.QWidget()
    page.image_draft_layout = qt.QHBoxLayout(page.image_drafts)
    page.image_draft_layout.setContentsMargins(0, 0, 0, 0)
    page.image_drafts.hide()
    page.composer_frame = qt.QFrame()
    page.composer_frame.setObjectName('lmComposerFrame')
    frame = qt.QVBoxLayout(page.composer_frame)
    frame.setContentsMargins(8, 4, 8, 8)
    frame.setSpacing(2)
    frame.addWidget(page.image_drafts)
    page.composer = Composer()
    page.composer.setPlaceholderText('Enter Message')
    page.composer.send_requested.connect(page.send)
    page.composer.image_pasted.connect(page.paste_screenshot)
    page.composer.image_paste_failed.connect(lambda error: page.status.setText(error))
    page.composer.setFixedHeight(72)
    page.composer.setAccessibleName('Message draft')
    frame.addWidget(page.composer)
    page.composer_toolbar = qt.QHBoxLayout()
    row = page.composer_toolbar
    row.setContentsMargins(2, 0, 2, 0)
    row.setSpacing(6)
    page.attach_button = qt.QToolButton(page.composer_frame)
    page.attach_button.setAutoRaise(True)
    page.attach_button.setIcon(chat_icon('plus'))
    page.attach_button.setIconSize(qt.QSize(18, 18))
    page.attach_button.setAccessibleName('Attach files')
    page.attach_button.setToolTip('Attach text files or images')
    page.attach_button.setPopupMode(qt.QToolButton.ToolButtonPopupMode.InstantPopup)
    attachments = qt.QMenu(page.attach_button)
    page.attach_text_action = attachments.addAction('Attach text files…', page.attach_files)
    page.attach_image_action = attachments.addAction('Attach images…', page.attachments.attach_images)
    page.attach_button.setMenu(attachments)
    page.attach_button.setFixedSize(28, 28)
    row.addWidget(page.attach_button)
    page.selection_button = qt.QToolButton(page.composer_frame)
    page.selection_button.setText('Paste Selection')
    page.selection_button.setAutoRaise(True)
    page.selection_button.setToolTip('Paste selected code from an open IDE editor in the selected Code project')
    page.selection_button.clicked.connect(page.attach_selection)
    row.addWidget(page.selection_button)
    row.addStretch(1)
    page.model = ModelPicker(page.composer_frame)
    page.model.setAccessibleName('Model for this conversation')
    row.addWidget(page.model)
    page.send_button = qt.QToolButton()
    page.send_button.setFixedSize(30, 30)
    page.send_button.setIconSize(qt.QSize(18, 18))
    page.send_button.setObjectName('lmSendStop')
    page.send_button.clicked.connect(page.send_or_stop)
    row.addWidget(page.send_button, 0, qt.Qt.AlignmentFlag.AlignBottom)
    frame.addLayout(row)
    dock.addWidget(page.composer_frame)
